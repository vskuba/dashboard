"""Прогон E2E по кнопке: задача стартует в процессе панели, страница не ждёт.

Прогон длится минуты — на случай × ширину приходится запуск браузера, а случаев
у установки будут десятки. Делать это прямо в обработчике запроса нельзя: ручка
обязана ответить сразу, иначе браузер оборвёт её по своему таймауту, а работа
останется идти в осиротевшем обработчике. Отвечает и заводит задача одно и то же
нажатие, но браузер работает уже в фоне: `asyncio.create_task`, а сам прогон
уводит запуски Chrome в отдельный поток (шапка `e2e_run`), и цикл событий панели
от него не встаёт.

⚠⚠ Раньше прогон уезжал в очередь задач (rq). Это стоило половины суток
отладочного времени на установке, где очередь не пуста: за спиной задач
конвейера прогон по кнопке простоивал в хвосте очереди часами, честно показывая
«Идёт прогон…» там, где работа ещё не начинала. Живая очередь не значит короткой
очереди: слушатели есть, очередь слушают — и стоят в ней все трое суток, и
никакой E2E_QUEUE_NAME этого не лечит. Задача в собственном процессе стартует
в ту же секунду и видна в том же журнале, где и вся панель.

## ⚠⚠ Single-flight: второй прогон не заводится

Ключ в Redis на время прогона — он переживает границу процесса: панель вправе
стоять в нескольких копиях, и вторая обязана увидеть, что первая уже работает.
Без ключа десять нажатий кнопки дают десять прогонов разом — это десять браузеров
на одной машине, и все они снимают одни и те же страницы. Кадры пишутся в разные
каталоги, так что молча портить друг друга не будут, но машина встанет.

⚠ Ключ снимается **по завершении**, а не по сроку: прогон по кнопке — не
расписание, и ждать после него нечего. Срок у ключа всё же есть, и это страховка
от потерянного процесса: убитая копия панели снять ключ не успеет, и без срока
кнопка осталась бы заблокированной навсегда.
"""

import asyncio

from logging_.logging_ import logger_exception, logger_info
from redis_.redis_ import redis_conn_get

# Страховка ключа single-flight: обычно ключ снимает сам прогон (см. шапку),
# срок нужен лишь на случай убитого посреди прогона процесса.
E2E_WORKER_JOB_TIMEOUT = 1800

# Ключ single-flight и его срок.
E2E_WORKER_FLIGHT_KEY = 'e2e_worker:flight'
E2E_WORKER_FLIGHT_TTL = E2E_WORKER_JOB_TIMEOUT + 120


def e2e_worker_enqueue() -> dict:
    """Завести прогон фоновой задачей, если он ещё не идёт.

    Returns:
        dict: `started` — завели ли прогон, `reason` — почему не завели.

    ⚠ Задача живёт в процессе панели и гибнет вместе с ним — для проверки
    интерфейса это верное поведение: перезапуск панели за перезапуском работ, а
    осиротевшая задача, догнавшая панель после рестарта, была бы хуже.
    """
    if not e2e_worker_flight_take():
        return {'started': False,
                'reason': 'Прогон уже идёт. Дождитесь его — второй браузер на '
                          'той же машине только замедлит первый.'}

    try:
        asyncio.get_running_loop().create_task(e2e_worker_task_run())
    except Exception:
        # ⚠ Ключ снимаем сами: задача не стартовала, и снять её некому —
        # кнопка осталась бы заблокированной до истечения срока.
        e2e_worker_flight_release()
        raise

    return {'started': True, 'reason': ''}


async def e2e_worker_task_run() -> dict:
    """Сама фоновая задача прогона.

    ⚠ Ключ single-flight снимается в `finally`: упавший прогон обязан отпустить
    кнопку так же, как удачный, иначе одна беда запирает проверку до срока.
    """
    from dashboard.src.page.e2e.e2e_run import e2e_run_all

    try:
        report = await e2e_run_all()
        logger_info(f"🧪 E2E по кнопке: тестов {report['tests']}, "
                    f"провалов {report['failed']}, сорвалось {report['errored']}, "
                    f"заняло {report['seconds']} с")
        return report
    except Exception as err:
        logger_exception(f'E2E: прогон по кнопке сорвался: {err}')
        raise
    finally:
        e2e_worker_flight_release()


def e2e_worker_running() -> bool:
    """Идёт ли прогон прямо сейчас — по ключу single-flight."""
    try:
        return bool(redis_conn_get().exists(E2E_WORKER_FLIGHT_KEY))
    except Exception:
        # Redis молчит — честнее сказать «не идёт» и дать нажать кнопку: задача
        # всё равно не заведётся без Redis, и ошибку человек увидит сразу, а не
        # в виде вечно «идущего» прогона.
        return False


def e2e_worker_flight_take() -> bool:
    """Занять single-flight; False — прогон уже идёт."""
    return bool(redis_conn_get().set(E2E_WORKER_FLIGHT_KEY, '1', nx=True,
                                     ex=E2E_WORKER_FLIGHT_TTL))


def e2e_worker_flight_release() -> None:
    """Освободить single-flight. Повторный вызов безвреден."""
    try:
        redis_conn_get().delete(E2E_WORKER_FLIGHT_KEY)
    except Exception as err:
        # Ключ протухнет сам по сроку: это и есть та страховка, ради которой
        # срок у него есть. Валить из-за этого прогон нечего.
        logger_exception(f'E2E: ключ прогона не снялся: {err}')
